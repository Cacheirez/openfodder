int main(int argc,char**argv){
 if(argc!=3 && argc!=4)return 2;
 const int density=argc==4?std::atoi(argv[3]):1;
 if(density!=1 && density!=8 && density!=12)return 2;
 const int fw=16*density,fh=14*density;
 int w,h,n;auto data=stbi_load(argv[1],&w,&h,&n,4);
 if(!data||w!=1353||h!=1162){stbi_image_free(data);return 3;}
 // Alpha >=16 bounds measured on generated C01; exclude nearly invisible fringe.
 const int left=406,top=176,right=969,bottom=1026;
 // Native original frame:16x14. Feet center (8,14); preserve aspect in a 10x14 box.
 std::ofstream out(argv[2]);out<<"// Generated by build_soldier_art.cpp from the original C01 PNG.\n#pragma once\n#include <array>\n#include <cstdint>\nnamespace openfodder {\ninline const std::array<uint32_t,"<<fw*fh<<">& SoldierArtPixels"<<(density==1?"":std::to_string(density))<<"(){\n static const std::array<uint32_t,"<<fw*fh<<"> pixels={{\n";
 for(int y=0;y<fh;++y)for(int x=0;x<fw;++x){
  uint32_t result=0;
  if(x>=3*density&&x<13*density){
   int x0=left+(x-3*density)*(right-left)/(10*density),x1=left+(x-3*density+1)*(right-left)/(10*density);
   int y0=top+y*(bottom-top)/fh,y1=top+(y+1)*(bottom-top)/fh;
   uint64_t a=0,r=0,g=0,b=0,count=uint64_t(x1-x0)*(y1-y0);
   for(int sy=y0;sy<y1;++sy)for(int sx=x0;sx<x1;++sx){auto p=data+4*(sy*w+sx);unsigned alpha=p[3]>=16?p[3]:0;a+=alpha;r+=p[0]*alpha;g+=p[1]*alpha;b+=p[2]*alpha;}
   if(a){result=(uint32_t(a/count)<<24)|(uint32_t(r/a)<<16)|(uint32_t(g/a)<<8)|uint32_t(b/a);}
  }
  out<<result<<"u,";if(x==fw-1)out<<"\n";
 }
 out<<" }};return pixels;\n}\n}\n";stbi_image_free(data);return out?0:4;
}
