"""Emit finite enemy source contracts; no artwork or observed-key inference."""
import argparse
from pathlib import Path
from inventory_enemy_states import ROOT, inventory


def contracts():
    result=[]
    for name,fmt in (('PC',0),('Amiga',1)):
        for slot in inventory()['platforms'][name]['slots']:
            actor=slot['actor_type'];m=slot['metadata']
            role=4 if actor==22 else 6 if actor==41 else 2
            people=0 if role!=2 else 4 if actor==106 else 0
            if role==2 and actor!=106:
                for context in slot['roles']:
                    people |= 1 if context['family']=='initial_person_zero_injury' else 2
            result.append(dict(format=fmt,type=actor,sheet=slot['sheet'],frame=slot['frame'],
                segment={'eGFX_IN_GAME':0,'eGFX_IN_GAME2':1}[m[1]],offset=int(m[0],0),
                columns=int(m[4],0),rows=int(m[5],0),modX=int(m[7],0),modY=int(m[8],0),
                palette=int(m[6],0) if fmt==0 else 0,role=role,personMask=people,
                invisible=slot['sheet']==0x7c,produced=slot['produced']))
    return sorted(result,key=lambda s:(s['format'],s['type'],s['sheet'],s['frame']))


def build():
    rows=contracts()
    fields=('format','type','sheet','frame','segment','offset','columns','rows','modX','modY','palette','role','personMask')
    lines=['// GPL-3.0-or-later. Generated by generate_enemy_pose_table.py from audited CF1 source.',
        '#pragma once','#include <cstddef>','namespace openfodder {',
        'struct EnemyNativeSlot { int '+','.join(fields)+'; bool invisible,produced; };',
        'static const EnemyNativeSlot CF1EnemyNativeSlots[]={']
    for row in rows:
        lines.append('    {'+','.join(str(row[k]) for k in fields)+','+
                     str(row['invisible']).lower()+','+str(row['produced']).lower()+'},')
    lines+=['};','inline size_t RequiredCF1EnemyNativeSlotCount() {',
        '    size_t count=0;for(const auto& slot:CF1EnemyNativeSlots)count+=slot.produced;return count;','}',
        'inline const EnemyNativeSlot* FindCF1EnemyNativeSlot(int format,int type,int sheet,int frame) {',
        '    for(const auto& slot:CF1EnemyNativeSlots)',
        '        if(slot.format==format && slot.type==type && slot.sheet==sheet && slot.frame==frame)return &slot;',
        '    return nullptr;','}','} // namespace openfodder','']
    return '\n'.join(lines)


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out',type=Path,default=ROOT/'Source/Utils/EnemyPoseTable.hpp')
    p.add_argument('--check',action='store_true');a=p.parse_args();text=build()
    if a.check:assert a.out.read_text(encoding='utf-8')==text,'Enemy native table drift'
    else:a.out.write_text(text,encoding='utf-8',newline='\n')
    rows=contracts();print(f"PASS {len(rows)} enemy contracts; {sum(r['produced'] for r in rows)} produced; explicit person/owner roles")
