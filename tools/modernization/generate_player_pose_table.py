"""Emit the bounded CF1 native pose contracts from source, never from gameplay logs."""
import argparse
import re
from pathlib import Path
from inventory_player_states import inventory, ROOT
from check_sprite_table_lengths import ARRAY, COMMENT, check


def contracts():
    catalog=inventory(include_art=False);entries=[]
    for platform,format_id in (('PC',0),('Amiga',1)):
        info=catalog['platforms'][platform]
        for row in info['required']:
            entries.append((format_id,row['actor_type'],row['sheet'],row['frame'],row['metadata'],False,2 if row['actor_type']==27 else 1))
        for row in info['hidden']:
            entries.append((format_id,0,row['sheet'],row['frame'],row['metadata'],True,1))
        text=(ROOT/f'Source/{platform}/SpriteData_{platform}.hpp').read_text(encoding='utf-8')
        _,tables=check(text);refs=tables[f'mSpriteSheetTypes_InGame_{platform}']
        arrays={name:[[v.strip() for v in row.split(',')] for row in re.findall(r'\{([^{}]+)\}',COMMENT.sub('',data))] for name,_,data in ARRAY.findall(text)}
        for frame,row in enumerate(arrays[refs[0x97]]):entries.append((format_id,22,0x97,frame,row,False,3))
    assert len(entries)==385
    return sorted(entries,key=lambda x:x[:4])


def build():
    catalog=inventory(include_art=False);entries=contracts()
    lines=['// GPL-3.0-or-later. Generated by generate_player_pose_table.py from CF1 source.',
           '#pragma once','#include <cstddef>','#include <cstdint>','namespace openfodder {',
           'struct PlayerNativeSlot { int format,type,sheet,frame,segment,offset,columns,rows,modX,modY,palette,role; bool invisible; };',
           'static const PlayerNativeSlot CF1PlayerNativeSlots[]={']
    for fmt,actor,sheet,frame,row,invisible,role in entries:
        segment={'eGFX_IN_GAME':0,'eGFX_IN_GAME2':1}[row[1]]
        palette=int(row[6],0) if fmt==0 else 0
        values=(fmt,actor,sheet,frame,segment,int(row[0],0),int(row[4],0),int(row[5],0),int(row[7],0),int(row[8],0),palette,role)
        lines.append('    {'+','.join(map(str,values))+','+('true' if invisible else 'false')+'},')
    lines+=['};','inline const PlayerNativeSlot* FindCF1PlayerNativeSlot(int format,int type,int sheet,int frame) {',
            '    for(const auto& slot:CF1PlayerNativeSlots)',
            '        if(slot.format==format && slot.type==type && slot.sheet==sheet && slot.frame==frame)return &slot;',
            '    return nullptr;','}',
            'inline bool IsCF1PlayerAnimation(int animation) {',
            '    switch(animation){'+''.join('case '+str(v)+':' for v in catalog['states'].values())+'return true;default:return false;}',
            '}','} // namespace openfodder','']
    return '\n'.join(lines)


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,default=ROOT/'Source/Utils/PlayerPoseTable.hpp');p.add_argument('--check',action='store_true');a=p.parse_args();text=build()
    if a.check:assert a.out.read_text(encoding='utf-8')==text,'Native pose table drift'
    else:a.out.write_text(text,encoding='utf-8',newline='\n')
    print('PASS 385 bounded native contracts (visible, hidden and owned shadow formats)')
