"""Emit CMake asset rules from the reviewed crop/placement manifest; preserve PNGs."""
from pathlib import Path
import argparse, hashlib, json
ROOT=Path(__file__).resolve().parents[2]
def rules():
 m=json.loads((ROOT/'assets/modernization/soldier-pilot-batch.json').read_text())
 text='''# Generated by tools/modernization/prepare_soldier_batch.py.
add_executable(openfodder_batch_builder tools/modernization/build_soldier_batch.cpp)
target_include_directories(openfodder_batch_builder PRIVATE "${CMAKE_CURRENT_SOURCE_DIR}/Source")
set(_pilot_headers)
'''
 for f in m['frames']:
  if(f['sheet'],f['frame'])==(7,0):continue
  source='assets/modernization/'+f['asset'];assert hashlib.sha256((ROOT/source).read_bytes()).hexdigest()==f['source_sha256']
  for d in (8,12):
   s,n=f['sheet'],f['frame'];header=f'pilot_{s}_{n}_{d}.hpp';symbol=f'Pilot{s}_{n}_{d}'
   args=' '.join(map(str,f['crop']+f['placement']))
   text+=f'''add_custom_command(OUTPUT "${{CMAKE_CURRENT_BINARY_DIR}}/{header}"
 COMMAND $<TARGET_FILE:openfodder_batch_builder> "${{CMAKE_CURRENT_SOURCE_DIR}}/{source}" "${{CMAKE_CURRENT_BINARY_DIR}}/{header}" {d} {symbol} {args}
 DEPENDS openfodder_batch_builder {source} assets/modernization/soldier-pilot-batch.json VERBATIM)
list(APPEND _pilot_headers "${{CMAKE_CURRENT_BINARY_DIR}}/{header}")
'''
 text+='''add_custom_target(openfodder_batch_assets DEPENDS ${_pilot_headers})
add_dependencies(openfodder openfodder_batch_assets)
add_dependencies(openfodder_art_sdl_tests openfodder_batch_assets)
add_executable(openfodder_batch_tests tools/modernization/test_soldier_batch.cpp)
add_dependencies(openfodder_batch_tests openfodder_batch_assets openfodder_art_hd_tests)
target_include_directories(openfodder_batch_tests PRIVATE "${CMAKE_CURRENT_SOURCE_DIR}/Source" "${CMAKE_CURRENT_BINARY_DIR}")
add_test(NAME soldier_batch_contract COMMAND $<TARGET_FILE:openfodder_batch_tests>)
'''
 return text
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args();out=ROOT/'tools/modernization/soldier_batch_assets.cmake';content=rules()
 if a.check:assert out.read_text()==content,'Regenerate asset rules'
 else:out.write_text(content)
